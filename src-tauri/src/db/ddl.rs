/// Quotes an identifier only when PostgreSQL requires it.
pub fn quote_ident(name: &str) -> String {
    let simple = name.chars().next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '$');
    if simple && !RESERVED.contains(&name) { name.to_string() } else { format!("\"{}\"", name.replace('"', "\"\"")) }
}

/// Quotes a string literal.
fn quote_literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

fn qualified(schema: &str, name: &str) -> String {
    format!("{}.{}", quote_ident(schema), quote_ident(name))
}

fn pg_error(error: tokio_postgres::Error) -> CommandError {
    CommandError::new(describe_pg_error(&error))
}

/// Looks up a relation's oid and relkind.
async fn relation(client: &Client, schema: &str, name: &str) -> CommandResult<(Oid, String)> {
    let row = client
        .query_opt("select c.oid, c.relkind::text from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = $1 and c.relname = $2", &[&schema, &name])
        .await
        .map_err(pg_error)?
        .ok_or_else(|| CommandError::new(format!("{} no longer exists", qualified(schema, name))))?;
    Ok((row.get(0), row.get(1)))
}

/// Renders one column definition line.
fn column_line(row: &tokio_postgres::Row) -> String {
    let name: String = row.get(0);
    let type_name: String = row.get(1);
    let not_null: bool = row.get(2);
    let default: Option<String> = row.get(3);
    let identity: Option<String> = row.get(4);
    let generated: Option<String> = row.get(5);
    let mut line = format!("    {} {}", quote_ident(&name), type_name);
    match (identity.as_deref(), generated.as_deref(), default) {
        (Some("a"), _, _) => line.push_str(" generated always as identity"),
        (Some("d"), _, _) => line.push_str(" generated by default as identity"),
        (_, Some("s"), Some(expr)) => line.push_str(&format!(" generated always as ({expr}) stored")),
        (_, _, Some(expr)) => line.push_str(&format!(" default {expr}")),
        _ => {}
    }
    if not_null {
        line.push_str(" not null");
    }
    line
}

/// Builds CREATE TABLE plus indexes and comments.
async fn table_ddl(client: &Client, schema: &str, name: &str, oid: Oid, relkind: &str) -> CommandResult<String> {
    let columns = client
        .query(
            "select a.attname::text, format_type(a.atttypid, a.atttypmod), a.attnotnull, pg_get_expr(d.adbin, d.adrelid),
                    nullif(to_jsonb(a) ->> 'attidentity', ''), nullif(to_jsonb(a) ->> 'attgenerated', ''), col_description(a.attrelid, a.attnum)
             from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
             where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped order by a.attnum",
            &[&oid],
        )
        .await
        .map_err(pg_error)?;
    let constraints = client
        .query(
            "select conname::text, pg_get_constraintdef(oid, true) from pg_constraint
             where conrelid = $1 and contype in ('p', 'u', 'c', 'f', 'x')
             order by case contype when 'p' then 0 when 'u' then 1 when 'c' then 2 when 'f' then 3 else 4 end, conname",
            &[&oid],
        )
        .await
        .map_err(pg_error)?;
    let indexes = client
        .query(
            "select pg_get_indexdef(i.indexrelid) from pg_index i
             where i.indrelid = $1 and not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid and c.conrelid = $1)
             order by 1",
            &[&oid],
        )
        .await
        .map_err(pg_error)?;
    let extras = client
        .query_one(
            "select obj_description($1::oid, 'pg_class'), case when $2::text = 'p' then pg_get_partkeydef($1::oid) end",
            &[&oid, &relkind],
        )
        .await
        .map_err(pg_error)?;

    let mut lines: Vec<String> = columns.iter().map(column_line).collect();
    lines.extend(constraints.iter().map(|c| format!("    constraint {} {}", quote_ident(c.get::<_, &str>(0)), c.get::<_, &str>(1))));
    let keyword = if relkind == "f" { "create foreign table" } else { "create table" };
    let mut ddl = format!("{keyword} {}\n(\n{}\n)", qualified(schema, name), lines.join(",\n"));
    if let Some(partition_key) = extras.get::<_, Option<String>>(1) {
        ddl.push_str(&format!("\npartition by {partition_key}"));
    }
    ddl.push_str(";\n");
    for index in &indexes {
        ddl.push_str(&format!("\n{};", index.get::<_, String>(0)));
    }
    if let Some(comment) = extras.get::<_, Option<String>>(0) {
        ddl.push_str(&format!("\n\ncomment on table {} is {};", qualified(schema, name), quote_literal(&comment)));
    }
    for column in columns.iter().filter(|c| c.get::<_, Option<String>>(6).is_some()) {
        let comment: String = column.get(6);
        ddl.push_str(&format!(
            "\ncomment on column {}.{} is {};",
            qualified(schema, name),
            quote_ident(column.get::<_, &str>(0)),
            quote_literal(&comment)
        ));
    }
    Ok(ddl.trim_end().to_string() + "\n")
}

/// Builds CREATE [MATERIALIZED] VIEW from the stored definition.
async fn view_ddl(client: &Client, schema: &str, name: &str, oid: Oid, relkind: &str) -> CommandResult<String> {
    let row = client.query_one("select pg_get_viewdef($1::oid, true)", &[&oid]).await.map_err(pg_error)?;
    let definition: String = row.get(0);
    let keyword = if relkind == "m" { "create materialized view" } else { "create or replace view" };
    let mut ddl = format!("{keyword} {} as\n{}\n", qualified(schema, name), definition.trim_end());
    if relkind == "m" {
        for index in client
            .query("select pg_get_indexdef(indexrelid) from pg_index where indrelid = $1::oid order by 1", &[&oid])
            .await
            .map_err(pg_error)?
        {
            ddl.push_str(&format!("\n{};", index.get::<_, String>(0)));
        }
    }
    Ok(ddl)
}

/// Builds CREATE SEQUENCE from pg_sequence.
async fn sequence_ddl(client: &Client, schema: &str, name: &str, oid: Oid) -> CommandResult<String> {
    let row = client
        .query_one(
            "select format_type(seqtypid, null), seqincrement::text, seqmin::text, seqmax::text, seqstart::text, seqcache::text, seqcycle
             from pg_sequence where seqrelid = $1",
            &[&oid],
        )
        .await
        .map_err(pg_error)?;
    Ok(format!(
        "create sequence {}\n    as {}\n    increment by {}\n    minvalue {}\n    maxvalue {}\n    start with {}\n    cache {}{};\n",
        qualified(schema, name),
        row.get::<_, String>(0),
        row.get::<_, String>(1),
        row.get::<_, String>(2),
        row.get::<_, String>(3),
        row.get::<_, String>(4),
        row.get::<_, String>(5),
        if row.get::<_, bool>(6) { "\n    cycle" } else { "" },
    ))
}

/// Returns pg_get_functiondef for a routine identified by name and identity arguments.
async fn routine_ddl(client: &Client, schema: &str, name: &str, arguments: &str) -> CommandResult<String> {
    let row = client
        .query_opt(
            "select p.oid, (to_jsonb(p) ->> 'prokind') from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where n.nspname = $1 and p.proname = $2 and pg_get_function_identity_arguments(p.oid) = $3",
            &[&schema, &name, &arguments],
        )
        .await
        .map_err(pg_error)?
        .ok_or_else(|| CommandError::new(format!("{}({arguments}) no longer exists", qualified(schema, name))))?;
    if row.get::<_, Option<&str>>(1) == Some("a") {
        return Ok(format!("-- {}({arguments}) is an aggregate; PostgreSQL cannot print its definition.\n", qualified(schema, name)));
    }
    let oid: Oid = row.get(0);
    let definition = client.query_one("select pg_get_functiondef($1::oid)", &[&oid]).await.map_err(pg_error)?;
    Ok(definition.get::<_, String>(0).trim_end().to_string() + ";\n")
}

/// Generates DDL for an explorer object.
/// `kind` is "relation" (tables and views), "sequence" or "routine"; `arguments` identifies a routine overload.
pub async fn object_ddl(session: &Session, schema: &str, name: &str, kind: &str, arguments: Option<&str>) -> CommandResult<String> {
    let client = &session.meta;
    match kind {
        "routine" => routine_ddl(client, schema, name, arguments.unwrap_or_default()).await,
        "sequence" => {
            let (oid, _) = relation(client, schema, name).await?;
            sequence_ddl(client, schema, name, oid).await
        }
        _ => {
            let (oid, relkind) = relation(client, schema, name).await?;
            match relkind.as_str() {
                "v" | "m" => view_ddl(client, schema, name, oid, &relkind).await,
                "S" => sequence_ddl(client, schema, name, oid).await,
                _ => table_ddl(client, schema, name, oid, &relkind).await,
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_only_when_needed() {
        assert_eq!(quote_ident("orders"), "orders");
        assert_eq!(quote_ident("order"), "\"order\"");
        assert_eq!(quote_ident("Customers"), "\"Customers\"");
        assert_eq!(quote_ident("a\"b"), "\"a\"\"b\"");
        assert_eq!(quote_ident("1abc"), "\"1abc\"");
    }
}
