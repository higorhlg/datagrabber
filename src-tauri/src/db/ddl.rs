//! Generates DDL for explorer objects from pg_catalog: tables (columns, constraints, partition
//! key, standalone indexes, comments), views and materialized views, sequences and routines.
//! Catalog columns that only exist in newer servers are read through to_jsonb so older servers
//! still work.

